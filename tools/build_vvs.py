"""Build frontend/vvs.js from tools/vvs/bookmark.src.js.

The bookmark ("li") runs inside VVS-dialog, started by the installer from the
address bar, as the logged-in installer. It finds the open case for a meter and
puts the LinkIQ report on it: uploads the files that are missing, writes the
fixed text to "Ny aktivitet" and sets the case status chosen in LinkIQ.
Needs Node (npx terser) once, at build time.

    python tools/build_vvs.py
"""
import json, pathlib, subprocess, urllib.parse

ROOT = pathlib.Path(__file__).resolve().parent.parent
SRC = ROOT / "tools" / "vvs" / "bookmark.src.js"
OUT = ROOT / "frontend" / "vvs.js"

minified = subprocess.run(["npx", "--yes", "terser@5", str(SRC), "-c", "-m"],
                          check=True, capture_output=True, text=True).stdout.strip()
url = "javascript:" + urllib.parse.quote(minified, safe="()!*'~-_.;,/?:@&=+$")
LOADER = ROOT / "tools" / "vvs" / "loader.src.js"
small = subprocess.run(["npx", "--yes", "terser@5", str(LOADER), "-c", "-m"],
                       check=True, capture_output=True, text=True).stdout.strip()
loader = "javascript:" + urllib.parse.quote(small, safe="()!*'~-_.;,/?:@&=+$")
OUT.write_text("/* Generated by tools/build_vvs.py from tools/vvs/bookmark.src.js and loader.src.js. Do not edit. */\n"
               "window.LINKIQ_VVS_BOOKMARK = " + json.dumps(url) + ";\n"
               "window.LINKIQ_VVS_CODE = " + json.dumps(minified) + ";\n"
               "window.LINKIQ_VVS_LOADER = " + json.dumps(loader) + ";\n", encoding="utf-8")
print(f"{OUT.relative_to(ROOT)}: li {len(loader)} characters (loader), full code {len(minified)}")

# The same code as a user script (Tampermonkey/Violentmonkey/Userscripts): a fixed "LinkIQ" button on
# every VVS-dialog page, and it starts by itself when the page was opened from LinkIQ (?liq=…).
src = SRC.read_text(encoding="utf-8").strip()
head, tail = "(async function () {", "})();"
if not (src.startswith("// ") and head in src and src.endswith(tail)):
    raise SystemExit("bookmark.src.js: unexpected shape")
body = src[src.index(head) + len(head):-len(tail)]
version = __import__("re").search(r"const VERSION = '([^']+)'", (ROOT / "frontend" / "app.js").read_text(encoding="utf-8")).group(1)
USER = ROOT / "frontend" / "linkiq-vvs.user.js"
USER.write_text("""// ==UserScript==
// @name         LinkIQ til VVS-dialog
// @namespace    linkiq
// @version      %s
// @description  Lægger LinkIQ-rapporten på sagen: filer, Ny aktivitet med faste ord og status.
// @match        https://vvsdialog.kmd.dk/*
// @grant        none
// @run-at       document-idle
// ==/UserScript==
// Generated by tools/build_vvs.py from tools/vvs/bookmark.src.js. Do not edit.
(function () {
  'use strict';
  async function liRun() {%s}
  var b = document.createElement('button');
  b.type = 'button'; b.textContent = 'LinkIQ';
  b.style.cssText = 'position:fixed;right:12px;bottom:12px;z-index:99998;padding:14px 18px;font:bold 17px Arial,sans-serif;' +
    'background:#ffd23f;color:#111;border:0;border-radius:28px;box-shadow:0 2px 10px rgba(0,0,0,.4)';
  b.onclick = function () { liRun(); };
  document.body.appendChild(b);
  // opened from LinkIQ: start by itself, once per page
  var key = 'liq-auto:' + location.pathname + location.search.slice(0, 80) + String(window.name).slice(0, 60);
  if ((/[?&]liq=/.test(location.search) || /^linkiq_j/.test(String(window.name))) && !sessionStorage.getItem(key)) {
    sessionStorage.setItem(key, '1');
    liRun();
  }
})();
""" % (version, body), encoding="utf-8")
print(f"{USER.relative_to(ROOT)}: user script")
